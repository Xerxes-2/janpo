#!/usr/bin/env bash
# JS 侧的关卡（M1 起）。`scripts/ci.sh` 会调它，也可以单独跑。
#
# 二十二道：TS/JS 的格式与 lint（Biome）→ **TS 类型闸门**（tsc --noEmit）→ **Agent 层的用例**
# （node --test，回放录制的响应）→ **prompt 的语义不变量**（扫一批真实对局）→ Fable 编译
# → Vite 产物 → 之后是**浏览器里的那十六趟**：**浏览器内跑引擎并与 dotnet 侧对拍**
# → **首页就是一局回放** → **牌桌上人看得见的八项** → **浏览器内跑黄金用例**
# → **浏览器内导出牌谱并回放** → **同一道闸门再走一整场** → **那道 key 闸门的反向自证**
# → **回显 key 的端点跑一手，牌谱里仍然没有它**
# → **URL 分享的载荷往返得回去** → **那道载荷闸门的反向自证**
# → **配桌那三项规则开关真的传到了引擎** → **四 LLM 同桌那一屏** → **思考气泡里的字来自那一手的决策记录**
# → **牌谱从外面进来的两条路（分享链接真往返、导入 JSON）**
# → **真人坐下把一局打完** → **ToolSearch 档的工具调用整条链路**。
#
# **前六道各是一条命令，后十六趟合成一条**（票 56）：它们从前各起一个 node 进程、一个 vite
# 服务器与一个 Chrome，现在跑在同一条跑道上（`web/scripts/verify-browser.mjs`：一个 Chrome
# 进程 + 一台 preview + 一台 dev server，十六趟各开自己的 page/context）。**一趟没少、
# 一条断言没拆**——每趟调的就是 `verify-*.mjs` 里那个函数，单跑（`pnpm run verify:board` 等）
# 与合并跑跑的是同一段代码。十六趟各自的来历写在 `verify-browser.mjs` 的那张表里。
#
# **那十六趟各开哪个地址**（票 71）：只有第七道与第八道开 `/`（它俩量的就是首页），
# 第二十道两个地址都开（分享链接从 `?table=1` 复制、导入入口在 `/` 上），
# 其余十三趟全开 `?table=1`——首页从此**自动播** Demo Paifu，而要点、要读牌桌的闸门
# 靠的是「默认暂停」那一页（`Playback.initial`）。
#
# 第七道是 19 票的验收：同一种子在浏览器里跑出的终局点数与顺位，必须与
# `janpo kyoku` / `janpo game` 逐项相同（跑的是 Vite 打包后的产物）。
# 它同时带着票 35：曳光弹现在藏在 `?dev=1` 后面，因此那一道先开不带开关的地址
# 确认开发向内容一样不在，再带开关去读那几行数。同一次打开顺带带着票 37 的反面：
# 首页的页脚里**必须**有一条回仓库的外链与一句许可（访客找到源码的唯一一条路）。
# 第八道是票 71 与 75 的验收：访客打开 `/` 什么都不用配，第一眼就是一桌牌在走
# （spec 的 story 1，ADR-0003 由 Demo Paifu 兑现），而且这一桌牌**拖得回去**（story 17）。
# **六条断言**：牌桌**在动**（隔一会儿采两次，手数必须不同）、页面上**没有配桌控件**、
# 有一条**去 `?table=1`** 的路（真点过去，且那一页默认暂停）、页脚照旧、
# **默认上帝视角**（裁决 71-8；带阳性对照——切回座位视角后他家必须扣回去）、
# **时间轴真的拖得动**（在滑块上真点而不是设 `value`：拖到 3/4 处、步进一个来回后
# DOM 逐字相同、拖回 0 是开局那一瞬、点局号落在那一局的开局帧）。
# 它顺带是「资产用 `fetch` 拉、不打进 bundle」那条路径的唯一无头证据。
# 第九道**牌桌八项**是票 44 的验收：**渲染给模型**那一侧有黄金用例逐字段钉着，
# **渲染给人**那一侧 M1 只有截图（两次信息缺失都是人肉眼发现的）。它在一局**真对局**里
# 走到立直、副露、手切与摸切同时在场的那一手，然后逐项核八项信息（手牌 / 河 / 副露 /
# 点数 / 供托与本场 / 宝牌指示牌 / 巡目 / 立直状态）与**方位**
# （四家画在哪个格子里，切视角时要跟着转）。
# 第十道是 21 票的验收：`tests/fixtures/golden/dual-target.json` 里的每条用例，
# 在浏览器里跑出的每个字段的每一行都要与文件一致（跑的是 Fable 的输出本身）。
# 同一份用例文件在 dotnet 侧由 `dotnet test` 的 `GoldenSuiteTests` 跑——**两侧读同一份数据**。
# 第十一道是 26 票的验收：浏览器里点一下「导出牌谱」真下下来一个文件，那份字节交回引擎
# fold 一遍，事件流逐条相同、点数与牌桌上的一致（ADR-0002 的回放）；它同时带着票 34 那条
# 「导出物里没有 key」。第十二道是票 39 的验收：同一个导出闸门再走一趟**整场**——
# 它那条点数断言在局中与终局读的是两个不同的权威（`GameState` / `Game`），
# 而只走几十手的那一趟永远碰不到后一种（票 39 未修时它在那里假红）。
# 第十三道是票 34 的反向自证：**一道从不失败的闸门等于没有闸门**，
# 因此每次 CI 都把那条断言按红一次（拌了 key 的导出物），并核实它红得就是因为那把 key。
# 第十四道是票 36 的验收：provider 的报错原文会流进牌谱的三处（`fallback` / `output` /
# 重试那一轮的 prompt），而自建网关完全可能把收到的 key 原样回显。那一道拿一个
# **真的会回显 key 的本机假端点**跑一手，导出牌谱，既查「里面没有 key」，
# 也查「打码记号在不在」（阳性对照：端点哪天不回显了，这道闸门就该告诉人它白给了）。
# 第十五道是票 77 的验收：URL 分享那一段载荷。引擎现打两场（东风战与半庄），
# 压一次、编一次、解一次，再把解出来那份交回引擎 fold：事件流逐条相同、终局点数与顺位相同。
# 它同时带着两样：**逐位置改坏一个字符**（每次要么红在「载荷读不动」、要么解出来逐字相同）与
# **审计三样一个都不上路**（thinking / prompt 尾部 / 一把假 key，自带阳性对照）。
# 第十六道是它的反向自证，理由与第十三道逐字相同。
# 第十七道是票 72 的验收：配桌上那三项规则开关（对局长度 / 赤宝牌 / 食断，spec 的 story 13）
# 真的从页面传到了引擎。它每一条断言读的都是**页面上点出来那一桌导出的牌谱**：先打完一整场
# 东风战（`start_kyoku` 的场风全是东、且赤牌真的进了事件流——后面那条「一张都没有」
# 的阳性对照），再把三项都拨到另一边而**不按重开**（牌谱里 `ruleset` 一个字段都不许变：
# **不许半场换规则**），按下重开之后再打完一整场半庄（南场真的打到了、赤宝牌一张不剩、
# 食断跟着关），最后把这一页重新打开一次，三项还在（localStorage）。
# 第十八道是票 73 的验收：**四 LLM 同桌**。两个本地假端点（一个答话、一个固定回 401，
# **一个字节都不出网**），一份模型档案坐两席、两席的人格各不同，第三席引用另一份
# 「坏 key 的档案」，座位 3 仍是 bot。一局打完之后逐条核导出的牌谱：`names` 是三个
# `provider/model` 加一个 `random`（**档案的名字与 key 都不在里面**）、那两席的 preamble
# **正文不同而渲染版本相同**（M2 对照实验的自变量只许有一个）、兜底**只涨在坏 key 那一席**
# 而这一局照样打得完、删掉一份还被座位引用的档案时页面把这件事说出来。
# 它还带第二程：上一版的 `janpo.llm.*`（含一把 key）迁成一份档案 + 老配置选中的那一席，
# 而且**只迁一次**——人拨回去的坐法不许被老键盖回来。
#
# 第十九道是票 76 的验收、票 74 把它扩成四席与并发：**思考气泡 + 同时问多席**。
# 第一程四席各配一个本机假端点（各回一句只可能从它那儿来的话）：四个气泡都在且**各说各的、
# 不串线**（MutationObserver 全程盯着，配一颗第一局就有多席同问的种子）、气泡与四家的
# 三排牌**矩形不相交**（读的是真坐标）、点开之后九样都在且牌桌摆出**那一手落定那一刻的
# 快照**、收起来逐字回到现在（只读），最后把座位 0 换到只回越界 id 的端点：它变「兜底」态，
# **而其余三席照样一手一手往前说**（一席坏了不拖累别席）。第二程三席共用一个**固定延迟**的
# 假端点、座位 3 仍是 bot：真出现 **≥2 席同时在想**，那一轮的墙钟**接近一份延迟而不是几份**
# （「真的并发了」的唯一硬证据），「在想」的气泡带着已等秒数与上限（data-waited /
# data-wait-limit，72-3 的代价），bot 那一席从头到尾一个气泡都没有。
#
# 第二十道是票 78 的验收：**牌谱从外面进来的两条路**。分享链接真往返一趟：
# `?table=1` 真打几手 → 点「复制分享链接」→ 读**真剪贴板**（授了权的）→ 断言那是一条
# 不带 `?table=1`、hash 里只有载荷的地址，且载荷解出的事件流与「导出牌谱」那份逐条相同
# → 打开那条地址：自动播、没有配桌面板、拖到末帧后点数与主持人那一桌一致，
# 而「为什么没有气泡」那句话指得回「导入牌谱 JSON」（票 76 的说明接票 78 的入口）。
# 导入那半：把导出的那份文件从首页导回去，末帧与主持人那一桌逐项一致（与第十一道互为反向）；
# 再导一份**带决策记录**的：气泡有话、气泡里就是那句 thinking——这是与分享链接的
# 关键差别（推理不上 URL），两种来源各验一次。最后坏链接与坏输入三连（不是 JSON /
# 缺字段 / 中间某局断掉）：各有中文原因，页面活着、正在播的那份回放一帧不动。
#
# 第二十一道是票 87 的验收：**桌边坐了个人**。真人坐座位 0、座位 1 交给一个本机假端点、
# 座位 2/3 是自带 bot，整段驱动跑在**页面内**（有牌点得动就点，没有就按「单步」），
# 一整场东风战打到终局：四家点数之和恒为 100000。中途把**整页 HTML** 抓下来，
# 里面每一个 `data-pai` 都必须落在「自家手牌 + 四家的河 + 四家的副露 + 宝牌指示牌」
# 那份预算里——**他家的手牌一张都不许有，连 `data-*` 都不许有**（spec 的 story 29）。
# 另外三件：上帝视角与别席视角的按钮**不在 DOM 里**（不是灰掉——票 81 把视角定成了信息闸门）、
# 对局中**一个思考气泡都没有**而 token 账单 > 0（阳性对照：那一席模型真被问过话，
# 因此「0 个气泡」量的不是一桌没人开口的空局）、`?dev=1` 的曳光弹**不给开**
# （挂账 22-A：它把带着四家配牌的 `start_kyoku` 印在同一张文档里；阴性对照是
# 同一条地址在没有真人时照旧开得了）。终局之后三样一起松开：视角按钮、气泡、曳光弹。

set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v pnpm >/dev/null 2>&1; then
  echo "找不到 pnpm。nix dev shell 里自带；宿主机上装法见 docs/development.md。" >&2
  exit 1
fi

# 无头验收要一个 Chrome/Chromium。跑批机器上有 /usr/bin/google-chrome-stable；
# 别处用 JANPO_CHROME 指过去，或 `pnpm dlx playwright install chromium`。
# 实在没有浏览器的环境（例：最小容器）可以 JANPO_NO_BROWSER=1 跳过**后十六趟**（它们合成一条
# 命令了，逐趟列在 `web/scripts/verify-browser.mjs` 的那张表里），前六道（biome / tsc /
# node --test / 语义不变量 / fable / vite build）照跑——
# 但那样浏览器里那十六趟验收一趟都没被验，别拿它当绿。
NO_BROWSER="${JANPO_NO_BROWSER:-0}"

echo "== pnpm install =="
(cd web && pnpm install --frozen-lockfile)

# --error-on-warnings：Biome 默认只拿 error 当失败，警告（包括它自己的配置弃用提示）会静静滑过去。
echo "== biome ci（TS/JS 的格式与 lint）=="
(cd web && node node_modules/@biomejs/biome/bin/biome ci --error-on-warnings .)

# 票 23 装上的（ADR-0005 说好的时机）：**只管 Agent 层与它的用例**，
# `src/generated`（Fable 的上万行输出）不在 tsconfig 的 include 里。
echo "== tsc --noEmit（Agent 层的类型闸门）=="
(cd web && pnpm run typecheck)

# **这一道不调真实 API**：它回放 `web/tests/fixtures/agent/` 里录制下来的响应
# （合法输出 / 越界 id / 格式跑偏 / 超时 / provider 报错）。
# 重录用 `pnpm run record:agent`，需要一把真 key，手动跑。
# 它还带着票 43 那道**新鲜度闸门**：改了 prompt 渲染器却没重算渲染器摘要，
# `render-version.test.ts` 当场红（改法：`pnpm run render-digest`）——没它的话，
# “改渲染＝废缓存”那一半就又静默了。
echo "== node --test（Agent 层的确定性用例）=="
(cd web && pnpm run test)

# 票 41 的验收：黄金用例钉的是**决策包**（结构化数据），前缀属性钉的是**字节单调**，
# 两道都不检查**渲出来的那句中文在日麻规则下成不成立**——票 40 那句「吃 来自对家」
# 就是从这个缺口漏过去的。这一道扫一批真实对局（`janpo decide --sequence`，本机跑引擎、
# **零网络请求**），逐手渲染三档再逐条断言，最后把十三条不变量与三道对拍各自**按红一次**
# （反向自证：一道从不失败的闸门等于没有闸门）。
echo "== prompt 的语义不变量（扫真实对局 + 逐条反向自证）=="
(cd web && node scripts/verify-invariants.mjs)

echo "== fable 编译（引擎 + Feliz 页面 → JS）=="
(cd web && pnpm run fable)

echo "== vite build =="
(cd web && node node_modules/vite/bin/vite.js build)

if [[ "$NO_BROWSER" == "1" ]]; then
  echo "== 浏览器里那十六趟（曳光弹对拍 / 首页回放 / 牌桌八项 / 黄金用例 / 牌谱导出两趟 / 两道 key 闸门 / 分享载荷两趟 / 配桌三项开关 / 四 LLM 同桌 / 思考气泡 / 牌谱从外面进来的两条路 / 真人坐席 / ToolSearch 工具链路）：按 JANPO_NO_BROWSER=1 跳过 =="
else
  # 十六趟一条命令（票 56）：一个 Chrome + 一台 preview + 一台 dev server，十六趟各开自己的
  # page/context。**每趟仍然单独跑得起来**——它红的时候会把单跑那一条命令抄给你
  # （`node scripts/verify-board.mjs` 之类），调试时照抄就只重跑那一趟。
  # 反向自证那一趟（拌了 key 的导出物必须当场红，且红得就是因为那把 key）也在里面，
  # 两种失法各报各的话，与从前那段 shell 逐字相同。
  echo "== 浏览器里那十六趟（共用一个浏览器进程与一台服务器）=="
  (cd web && node scripts/verify-browser.mjs)
fi

echo "== JS 侧全绿 =="
