/**
 * ToolSearch 档那件**多出来的能力**（票 94）：`what_if` —— 单步 what-if 查询。
 *
 * ## 这一档加的是「自己去问」，不是又一批算好的数值
 *
 * `CONTEXT.md` 的 `ScaffoldTier` 把判据写死了：Bare 与 Assisted 之间那条线是「感知 vs 计算」，
 * 而 **ToolSearch 加的是自己去问的能力，不是又一批算好的数值，因此不落在这条判据的两端上**。
 * 落地因此是：**ToolSearch 的正文就是 Bare 的正文**（一个算好的数都不推给它），
 * 另给它一个工具，让它**自己挑几张牌去问**向听数 / 有效牌 / 危险度。
 * 把 Assisted 那一节也一起给它，就等于「又一批算好的数值」+ 一个没人会用的工具
 * ——那一档与 Assisted 只差账单，不差别的（取舍与被否决的另一读法见 `DECISIONS.md` 94-1）。
 *
 * ## 答案与 Assisted 档出自**同一个函数**
 *
 * 查询的答案不另算一遍：它就是 `prompt.ts` 里 Assisted 档用的那两个函数
 * （`trial` 与 `dangerLine`）对着**同一份 `decision.scaffold`**（引擎的 `Scaffold.calculate`
 * 算出来的那一份，恒随包过界）渲出来的**同一行字节**。
 * `tests/agent/what-if.test.ts` 逐条断言这件事：同一个 id，工具答的那一行与 Assisted 档
 * 印的那一行**逐字节相同**——「同一个函数」因此不是一句承诺，是一条可执行的等式。
 *
 * ## 一手最多问几次，以及为什么是这个数
 *
 * `WHAT_IF_LIMIT = 4`，三个理由（缺一条这个数就成了随手写的）：
 *
 * 1. **手牌张数**：一手最多 14 张打得出去。问满 14 次拿到的就是 Assisted 那张表本身
 *    ——那不是「自己去问」，是换条路把同一批算好的数拿全，这一档的自变量当场没了。
 *    4 次是「先排掉明显要留的，再在剩下的候选里挑」这一步的规模。
 * 2. **账单**：每多问一次就多发一次请求，可缓存前缀按折扣价、**尾部每次全价**。
 *    封在 4 次，单手最坏是 5 次请求（4 问 + 1 答），账单的上界因此是有限的常数。
 * 3. **延迟**：票 79 实测直觉档单手中位 1.7 s，5 倍是 8.5 s——仍在思考档
 *    （同一份实测 11.8 s）之下，一场东风战因此还跑得完。
 *
 * **问满了就把这个工具收走**（`loop.ts`：`whatIfIds` 传空表 = 这一轮不给它）：
 * 上限不是靠「求模型别再问了」，是靠**它压根没得可调**。这一手因此照常打完，不会卡死。
 */

/** 工具名。**判读回答时也认它**（`loop.ts` 把它与 `choose_action` 分开处理）。 */
export const WHAT_IF = "what_if";

/** 一手最多问几次。理由见文件头那三条（手牌张数 / 账单 / 延迟）。 */
export const WHAT_IF_LIMIT = 4;

/**
 * 问过的一次。**只记 id 不记答案**：答案是 (决策包 + id) 的派生物，
 * 每次渲染现算——存一份下来就多一个会与决策包对不上的东西。
 */
export interface WhatIf {
  /** 问的是哪一条动作（这一包内的 id）。 */
  id: number;
}

/**
 * 固定 preamble 里多出来的那一段（**只有 ToolSearch 档有**）。
 *
 * **位置是第③段之后、第④段之前**（`prompt.ts` 的 `preambleFor`）：preamble 的四段依次是
 * ①开场两句 ②【你要争的是什么】 ③【怎么读这份 prompt】 ④三段结构说明，**这一段插在 ③ 与 ④ 之间**。
 * 它在**可缓存前缀**里，因此一场只付一次全价，之后按缓存价——写进尾部的话就是每手全价，
 * 而它一个字都不随局面变。
 *
 * **不写中文牌名、不写 mjai 的动作 wire 名**（`RULES.mjaiOnly` 会当场红），
 * 也不解释怎么读那几个数——那几行本来就与 Assisted 档逐字节相同，读法归 `CONTEXT.md`。
 */
export const WHAT_IF_PREAMBLE = [
  "【打之前你可以先问】",
  `除了 choose_action，你还可以调用 ${WHAT_IF} 工具：给它一条打牌动作的 action_id，`,
  "引擎会按这一手真实可见的牌算出「打完它之后」的向听数、有效牌与危险度，原样回给你。",
  "它给的是事实，不是建议，也不替你选牌；不问也可以，直接出牌完全允许。",
  `一手最多问 ${WHAT_IF_LIMIT} 次，问满之后这个工具就不再给你，那时直接调 choose_action 出牌。`,
  "问过的每一次都会写在下面那一节里（同一个 action_id 问两遍也算两次）。",
].join("\n");

/**
 * 这一手还能问几次 → 还给不给这个工具。
 *
 * **上限是这里执行的**，不是靠 prompt 里那句话求模型自觉：返回空表时
 * `piai.ts` 根本不把 `what_if` 放进 `tools`，模型于是**调不出来**。
 */
export function whatIfExhausted(asked: readonly WhatIf[]): boolean {
  return asked.length >= WHAT_IF_LIMIT;
}
